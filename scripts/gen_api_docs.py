#!/usr/bin/env python3
"""Generate docs/guide/api.md from the public signatures and docstrings.

Python objects are inspected from an importable fbfast (the installed wheel, or
dist/vendor when it is not installed); native classes use the stub docstrings.
``--check`` fails when the reference is stale.
"""
from __future__ import annotations

import argparse
import ast
import importlib
import inspect
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
GUIDE = ROOT / "docs/guide/api.md"
STUB = ROOT / "python/fbfast/_native.pyi"

SECTIONS: list[tuple[str, list[str]]] = [
    ("Pools", ["Pool"]),
    ("Snapshots", ["Snapshot"]),
    ("Several queries at once", ["Query", "Results", "Done", "QueryGroup", "AsyncQueryGroup"]),
    ("Streams", ["Stream", "AsyncStream", "JsonStream", "AsyncJsonStream", "ArrowStream",
                 "AsyncArrowStream"]),
    ("Named pools", ["init_pool", "init_pool_async", "get_pool", "close_pool",
                     "close_pool_async"]),
    ("Client information", ["build_info", "client_info"]),
    ("Values", ["TimeWithZone"]),
]
NATIVE = ["FirebirdConfig", "ArrowBatch", "ArrowSchema"]
TYPES = ["DEFAULT", "DefaultTimeout", "Timeout", "Params", "PoolStats", "QueryTrace",
         "PhaseTrace", "SessionInfo"]
DEPRECATED = {"warmup_sync", "close_sync", "clear_statement_cache_sync", "snapshot_async",
              "init_pool_sync", "close_pool_sync"}


def load(path: Path | None) -> Any:
    """Prefer an explicit directory, then this checkout's dist/vendor, then site-packages."""
    sys.dont_write_bytecode = True  # never leave __pycache__ in a verified vendor copy
    vendor = ROOT / "dist/vendor"
    if path is None and (vendor / "fbfast/__init__.py").is_file():
        path = vendor
    if path is not None:
        sys.path.insert(0, str(path))
    return importlib.import_module("fbfast")


def doc(obj: Any) -> str:
    text = inspect.getdoc(obj) or ""
    return text.strip()


def signature(name: str, obj: Any) -> str:
    try:
        text = str(inspect.signature(obj))
    except (TypeError, ValueError):
        return name
    # Postponed annotations are strings; show them as written in the source.
    return name + re.sub(r"(: |-> )'([^']*)'", r"\1\2", text)


def members(cls: type) -> list[tuple[str, Any]]:
    found = []
    for name in sorted(dir(cls)):
        if name.startswith("_") and name not in ("__enter__", "__aenter__", "__iter__",
                                                 "__aiter__", "__getitem__"):
            continue
        attribute = inspect.getattr_static(cls, name)
        if name in DEPRECATED or getattr(attribute, "__module__", "fbfast") == "builtins":
            continue
        if isinstance(attribute, (staticmethod, classmethod)):
            attribute = attribute.__func__
        if isinstance(attribute, property) or callable(attribute):
            found.append((name, attribute))
    return found


def render_class(name: str, cls: type) -> list[str]:
    lines = [f"### `{name}`", "", doc(cls), ""]
    for member, attribute in members(cls):
        if isinstance(attribute, property):
            summary = doc(attribute).splitlines()[0] if doc(attribute) else ""
            lines += [f"- **`{member}`** (property): {summary}", ""]
            continue
        lines += [f"#### `{name}.{signature(member, attribute)}`", ""]
        text = doc(attribute)
        if text:
            lines += [text, ""]
    return lines


def native_docs() -> list[str]:
    tree = ast.parse(STUB.read_text())
    lines: list[str] = []
    for node in tree.body:
        if not isinstance(node, ast.ClassDef) or node.name not in NATIVE:
            continue
        lines += [f"### `{node.name}`", "", (ast.get_docstring(node) or "").strip(), ""]
        if node.name == "FirebirdConfig":
            lines += ["Every option is listed in [configuration.md](configuration.md).", ""]
        for item in node.body:
            if isinstance(item, ast.FunctionDef) and not item.name.startswith("_"):
                text = (ast.get_docstring(item) or "").strip()
                kind = "property" if any(isinstance(d, ast.Name) and d.id == "property"
                                         for d in item.decorator_list) else "method"
                first = text.splitlines()[0] if text else ""
                lines.append(f"- **`{item.name}`** ({kind}): {first}")
        lines.append("")
    return lines


def render(fb: Any) -> str:
    lines = [
        "# API reference",
        "",
        "<!-- Generated by scripts/gen_api_docs.py; do not edit. -->",
        "",
        "Naming rule: methods without a suffix block; `*_async` methods and `aclose` are",
        "coroutines. Parameters bind positionally to `?` placeholders. Module functions",
        "such as `fbfast.fetch_all(sql, params, pool=\"default\")` are shortcuts for",
        "`get_pool(pool).fetch_all(sql, params)` and take the same arguments.",
        "",
    ]
    for title, names in SECTIONS:
        lines += [f"## {title}", ""]
        for name in names:
            obj = getattr(fb, name)
            if inspect.isclass(obj):
                lines += render_class(name, obj)
            else:
                lines += [f"### `{signature(name, obj)}`", "", doc(obj), ""]
    lines += ["## Configuration and Arrow types", ""] + native_docs()
    lines += ["## Typing helpers", ""]
    for name in TYPES:
        obj = getattr(fb, name)
        text = doc(obj) if inspect.isclass(obj) else ""
        lines.append(f"- **`{name}`**{': ' + text.splitlines()[0] if text else ''}")
    lines += ["", "## Errors", "",
              "All errors derive from `FbFastError` and carry `phase`, `sqlstate`,",
              "`native_codes` and `cleanup_errors`. See [errors.md](errors.md).", ""]
    errors = sorted((obj for obj in vars(fb).values()
                     if inspect.isclass(obj) and issubclass(obj, fb.FbFastError)),
                    key=lambda cls: (len(cls.__mro__), cls.__name__))
    for cls in errors:
        bases = ", ".join(base.__name__ for base in cls.__bases__)
        lines.append(f"- **`{cls.__name__}`**({bases}): {doc(cls).splitlines()[0]}")
    deprecated = ", ".join(f"`{name}`" for name in sorted(DEPRECATED))
    lines += ["", "## Deprecated (removed in 0.4.0)", "",
              f"{deprecated}: aliases kept for one release; they emit `DeprecationWarning`.", ""]
    text = "\n".join(lines)
    while "\n\n\n" in text:
        text = text.replace("\n\n\n", "\n\n")
    return text.rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the reference is stale")
    parser.add_argument("--from", dest="source", type=Path,
                        help="directory containing the fbfast package to inspect")
    args = parser.parse_args()
    content = render(load(args.source))
    if args.check:
        if not GUIDE.is_file() or GUIDE.read_text() != content:
            raise SystemExit("docs/guide/api.md is stale; run scripts/gen_api_docs.py")
        print("API reference matches the package")
        return
    GUIDE.parent.mkdir(parents=True, exist_ok=True)
    GUIDE.write_text(content)
    print(f"Wrote {GUIDE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
