#!/usr/bin/env python3
"""Generate llms-full.txt: llms.txt with the assistant rules and guides inlined.

Sources are llms.txt, python/fbfast/llms.txt and docs/guide/*.md (the guides
that exist). Relative Markdown links become absolute GitHub links pinned to the
release tag, so the file stays valid outside the repository. ``--check`` fails
when the committed file is stale.
"""
from __future__ import annotations

import argparse
import posixpath
import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "llms-full.txt"
REPOSITORY = "https://github.com/rafael-peter/fbfast"
GUIDES = ["recipes", "errors", "troubleshooting", "configuration", "performance", "api"]
LINK = re.compile(r"\]\(([^)\s]+)\)")


def tag() -> str:
    version = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]["version"]
    return f"v{version}"


def absolute(text: str, source: Path, ref: str) -> str:
    """Rewrites relative link targets of ``source`` to pinned GitHub URLs."""
    base = source.parent.relative_to(ROOT).as_posix()

    def replace(match: re.Match[str]) -> str:
        target = match.group(1)
        if re.match(r"^[a-z]+:|^#", target):
            return match.group(0)
        path, _, anchor = target.partition("#")
        resolved = posixpath.normpath(posixpath.join(base, path))
        kind = "tree" if (ROOT / resolved).is_dir() else "blob"
        suffix = f"#{anchor}" if anchor else ""
        return f"]({REPOSITORY}/{kind}/{ref}/{resolved}{suffix})"

    return LINK.sub(replace, text)


def render() -> str:
    ref = tag()
    parts = [(ROOT / "llms.txt").read_text().rstrip()]
    sources = [ROOT / "python/fbfast/llms.txt"]
    sources += [ROOT / f"docs/guide/{name}.md" for name in GUIDES]
    for source in sources:
        if not source.is_file():
            continue
        relative = source.relative_to(ROOT).as_posix()
        body = absolute(source.read_text().rstrip(), source, ref)
        parts.append(f"<!-- Source: {REPOSITORY}/blob/{ref}/{relative} -->\n\n{body}")
    footer = ("<!-- Generated by scripts/gen_llms_full.py from llms.txt, "
              "python/fbfast/llms.txt and docs/guide/; do not edit. -->")
    return "\n\n---\n\n".join(parts) + "\n\n" + footer + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if llms-full.txt is stale")
    args = parser.parse_args()
    text = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != text:
            raise SystemExit("llms-full.txt is stale; run scripts/gen_llms_full.py")
        print("llms-full.txt is current")
        return
    OUTPUT.write_text(text)
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
