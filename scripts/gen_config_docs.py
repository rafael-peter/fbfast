#!/usr/bin/env python3
"""Generate docs/guide/configuration.md from the FirebirdConfig stub docstring.

The stub (python/fbfast/_native.pyi) is the single source: IDEs show it and this
script renders the same text as a table. ``--check`` fails when the guide is
stale; tests/packaging/test_config_docs.py also compares it with the Rust FIELDS.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STUB = ROOT / "python/fbfast/_native.pyi"
GUIDE = ROOT / "docs/guide/configuration.md"
ENTRY = re.compile(r"^            (\w+): (.*?)(?: \[env (FB_\w+); (default (.*)|required)\])?$")

HEADER = """# Configuration

<!-- Generated by scripts/gen_config_docs.py from python/fbfast/_native.pyi; do not edit. -->

`FirebirdConfig()` resolves every option from, in order: the explicit keyword
argument, the `FB_<NAME>` environment variable, the same variable in a `.env`
file in the current directory, and the default below. `database`, `user` and
`password` are required. Construction validates all values and never connects.

```python
import fbfast

config = fbfast.FirebirdConfig()                      # FB_* variables and .env
config = fbfast.FirebirdConfig(pool_size=4, query_timeout=10.0, env_file=False)
config = fbfast.FirebirdConfig.from_env("FB_BI_")     # FB_BI_HOST, FB_BI_DATABASE...
```

In the environment and `.env`, numbers are text, booleans accept
`true/false`, `1/0` and `yes/no`, and `none` means `None`. Durations are
seconds. An explicit `None` wins over the environment for options that accept
it. Unknown options and invalid values raise `ConfigurationError`.

| Option | Environment | Default | Description |
|---|---|---|---|
"""


def entries(stub: str = "") -> list[tuple[str, str, str, str]]:
    text = stub or STUB.read_text()
    block = text.split("class FirebirdConfig:", 1)[1].split("        Args:\n", 1)[1]
    block = block.split("\n\n", 1)[0]
    rows = []
    for line in block.splitlines():
        match = ENTRY.match(line)
        if not match:
            raise SystemExit(f"Unparseable FirebirdConfig Args line: {line!r}")
        name, description, env, kind, default = match.groups()
        if name == "env_file":
            continue
        if env is None:
            raise SystemExit(f"{name}: missing [env FB_...; default ...] marker")
        rows.append((name, env, "required" if kind == "required" else default, description))
    return rows


def render() -> str:
    lines = [HEADER.rstrip("\n")]
    for name, env, default, description in entries():
        cell = description.replace("|", "\\|")
        lines.append(f"| `{name}` | `{env}` | `{default}` | {cell} |")
    lines.append("")
    lines.append("`env_file`: path of a dotenv file (str) or `False` to skip it. Omitted: read")
    lines.append("`.env` in the current directory if it exists. There is no `FB_ENV_FILE`.")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the guide is stale")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not GUIDE.is_file() or GUIDE.read_text() != content:
            raise SystemExit("docs/guide/configuration.md is stale; run scripts/gen_config_docs.py")
        print("Configuration guide matches the stub")
        return
    GUIDE.parent.mkdir(parents=True, exist_ok=True)
    GUIDE.write_text(content)
    print(f"Wrote {GUIDE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
