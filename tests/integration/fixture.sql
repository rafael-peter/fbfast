-- Deliberately privileged routine used to prove that a read-only transaction is
-- not a SQL sandbox: generator increments survive rollback. The normal test role
-- receives no EXECUTE privilege on this procedure.
CREATE SEQUENCE FBFAST_SIDE_EFFECT_SEQUENCE;
SET TERM ^;
CREATE PROCEDURE FBFAST_SIDE_EFFECT RETURNS (V BIGINT)
AS
BEGIN
    V = GEN_ID(FBFAST_SIDE_EFFECT_SEQUENCE, 1);
    SUSPEND;
END^
SET TERM ;^
REVOKE EXECUTE ON PROCEDURE FBFAST_SIDE_EFFECT FROM PUBLIC;
COMMIT;

